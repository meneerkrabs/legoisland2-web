#!/usr/bin/env node
// Runs the browser's LEGO 3D generator (src/mods/lego3d/gen) in node over the game folder and writes the result as a mod folder (LI2 Mod Manager layout) for looking at, for the
// headless QA scenes (LE2_MODS=<dir>) and for tests. Same code as the browser, same pack.
//   node tools/lego3d/build-mod.mjs [--pack FILE] [--out DIR] [--only z02LGI,Bricks] [--gen textures,characters | --gen=-studs] [--report FILE]
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { Pack } from '../../src/mods/lego3d/pack.ts';
import { generateArchive } from '../../src/mods/lego3d/gen/index.ts';
import { archive, archiveNames, EXTRACT } from './lib.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const args = process.argv.slice(2);
const opt = (n, d) => { const i = args.indexOf(n); return i < 0 ? d : args[i + 1]; };
const PACK = opt('--pack', path.join(here, '../../src/mods/lego3d/data/lego3d.pack'));
const OUT = opt('--out', path.join(EXTRACT, 'mods/lego3d-build'));
const only = (opt('--only', '') || '').split(',').filter(Boolean).map((s) => s.toLowerCase());
const gens = (opt('--gen', '') || '').split(',').filter(Boolean);
const pack = Pack.open(new Uint8Array(fs.readFileSync(PACK)));
console.log(`pack ${pack.version}: ${pack.names().length} blobs`);
fs.rmSync(OUT, { recursive: true, force: true });
fs.mkdirSync(OUT, { recursive: true });
fs.writeFileSync(path.join(OUT, 'info.txt'), 'LEGO 3D (generated)\ntools/lego3d/build-mod.mjs\nGenerated by the LEGO 3D generator from the data pack and the local game files. Local only: contains pieces of the game.\n');
const report = {};
for (const name of archiveNames()) {
  if (only.length && !only.includes(name.toLowerCase())) continue;
  const a = archive(name);
  const r = await generateArchive(pack, name, a, async (n) => archive(n), gens);
  if (!r.files.size) continue;
  report[name] = { files: r.files.size, bytes: [...r.files.values()].reduce((s, b) => s + b.length, 0), by: Object.fromEntries([...r.by.values()].reduce((m, g) => m.set(g, (m.get(g) ?? 0) + 1), new Map())), stats: r.stats, ms: r.ms, log: r.log.slice(0, 50) };
  for (const [m, b] of r.files) { const f = path.join(OUT, '_data', name, m); fs.mkdirSync(path.dirname(f), { recursive: true }); fs.writeFileSync(f, b); }
  console.log(name, JSON.stringify({ files: report[name].files, MB: +(report[name].bytes / 1e6).toFixed(2), by: report[name].by, ms: r.ms }));
}
const rf = opt('--report', '');
if (rf) fs.writeFileSync(rf, JSON.stringify(report, null, 1));

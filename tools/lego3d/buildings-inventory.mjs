#!/usr/bin/env node
// Building / structure inventory of the LEGO 3D option (docs/re/lego3d.md section 18): for every record of the table BLD (buildings-table.mjs) the LOD meshes of its model with the game's triangle count, the groups
// (flat colour, textured, translucent, moving = MATL not identity) and what the generators write over each LOD (pack -> generator, the browser's path: `by` = which generator wrote the member, triangles after).
//   node tools/lego3d/buildings-inventory.mjs [--md] [--json out.json] [--zones z02LGI,...]
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { archive, memberOf, scene } from './lib.mjs';
import { parseMsh } from '../../src/formats/msh.ts';
import { Pack } from '../../src/mods/lego3d/pack.ts';
import { generateArchive } from '../../src/mods/lego3d/gen/index.ts';
import { BLD } from './buildings-table.mjs';
const here = path.dirname(fileURLToPath(import.meta.url));
const args = process.argv.slice(2);
const ji = args.indexOf('--json'); const jsonOut = ji >= 0 ? args.splice(ji, 2)[1] : null;
const zi = args.indexOf('--zones'); const zonesOnly = zi >= 0 ? args.splice(zi, 2)[1].split(',') : [];
const md = args.includes('--md');
const pack = Pack.open(new Uint8Array(fs.readFileSync(path.join(here, '../../src/mods/lego3d/data/lego3d.pack'))));
const rows = [];
for (const [z, list] of Object.entries(BLD)) {
  if (zonesOnly.length && !zonesOnly.includes(z)) continue;
  const sc = scene(z), arch = archive(z);
  const gen = await generateArchive(pack, z, arch, async () => null, []);
  for (const [idx, L, H, mesh] of list) {
    const r = sc.records[idx];
    const parts = r.model.parts.filter(Boolean).map((p) => ({ lod: p.lod, path: sc.meshPaths[p.mesh] }));
    const lods = parts.map((p) => {
      const member = memberOf(p.path), e = arch.find(member);
      let tris = null, groups = null, moving = 0, trans = 0;
      if (e) {
        const m = parseMsh(arch.read(e)); tris = m.indices.length / 3; groups = m.groups.length;
        trans = m.groups.filter((g) => g.flags & 2).length;
        if (m.gtom && m.matl) { const idn = new Set(); for (let i = 0; i < m.matl.length / 9; i++) { const t = m.matl.subarray(i * 9, i * 9 + 9); if (t.some((v, k) => v !== [0, 0, 0, 0, 0, 0, 1, 1, 1][k])) idn.add(i); } moving = [...m.gtom].filter((g) => idn.has(g)).length; }
      }
      const k = [...gen.files.keys()].find((x) => x.toLowerCase() === member.toLowerCase());
      let after = null, by = null;
      if (k) { const m = parseMsh(gen.files.get(k)); after = m.indices.length / 3; by = gen.by.get(k); }
      return { lod: p.lod, file: p.path.replace(/^.*[\\/]/, ''), tris, groups, moving, trans, after, by };
    });
    rows.push({ zone: z, idx, name: r.name.trim(), mesh, L, H, lods });
  }
}
if (jsonOut) fs.writeFileSync(jsonOut, JSON.stringify(rows, null, 1));
const fmt = (l) => `${l.lod}: ${l.tris ?? '?'}${l.after != null ? ` -> ${l.after} ${l.by}` : ''}`;
if (md) {
  console.log('| zone | rec (index) | mesh | LODs (game tris -> generated by) | groups (translucent / moving) |\n|---|---|---|---|---|');
  for (const r of rows) console.log(`| ${r.zone} | ${r.name} (${r.idx}) | ${r.mesh} | ${r.lods.map(fmt).join('; ')} | ${r.lods[0].groups} (${r.lods[0].trans} / ${r.lods[0].moving}) |`);
} else for (const r of rows) console.log(r.zone, r.idx, r.name, r.mesh, r.lods.map(fmt).join(' '));

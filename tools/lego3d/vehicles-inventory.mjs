#!/usr/bin/env node
// Vehicle inventory of the LEGO 3D option (docs/re/lego3d.md section 17): every vehicle-like record of every zone (by the mesh name of its LOD parts), the LOD meshes of its model with the
// game's triangle count, what the generators write over it (pack -> generator, the browser's path: `by` = which generator wrote the member, triangles after), and the groups that move (MATL != identity).
//   node tools/lego3d/vehicles-inventory.mjs [--md] [--json out.json]
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { archive, archiveNames, memberOf, scene } from './lib.mjs';
import { parseMsh } from '../../src/formats/msh.ts';
import { Pack } from '../../src/mods/lego3d/pack.ts';
import { generateArchive } from '../../src/mods/lego3d/gen/index.ts';
const here = path.dirname(fileURLToPath(import.meta.url));
const args = process.argv.slice(2);
const ji = args.indexOf('--json'); const jsonOut = ji >= 0 ? args.splice(ji, 2)[1] : null;
const md = args.includes('--md');
const VEH = /^(jetski|ambulance|speedster|speeder|speedboat|dingy|boat|group\d|heli_|policeheli|police_chopper|helic|locomotive|loco_|steam_train|seaplane|airstrip_seaplane|airstrip_biplane|biplane|microlight|policecar|shuttle|fishship|solaarwing|hoverboarddeck|skboard|sandboard|pterodactyl|pter_|ripple_|wake_|ripp_|rippl|splash|prop|seaplane_prop|biplane_prop|flot_float|balloon|hotb|para_chute|dolphskin|clambot|cannon_nowheel|cartpos)/i;
const pack = Pack.open(new Uint8Array(fs.readFileSync(path.join(here, '../../src/mods/lego3d/data/lego3d.pack'))));
const rows = [];
for (const z of archiveNames().filter((n) => /^z\d/.test(n))) {
  let sc; try { sc = scene(z); } catch { continue; }
  const arch = archive(z);
  const gen = await generateArchive(pack, z, arch, async () => null, []);
  const seen = new Map();
  for (const r of sc.records) {
    if (!r.model) continue;
    const parts = r.model.parts.filter(Boolean).map((p) => ({ lod: p.lod, file: (sc.meshPaths[p.mesh] ?? '').replace(/^.*[\\/]/, ''), path: sc.meshPaths[p.mesh] }));
    if (!parts.length || !VEH.test(parts[0].file)) continue;
    const key = `${parts.map((p) => p.file).join(',')}`;
    if (seen.has(key)) { seen.get(key).records.push(r.name); continue; }
    const lods = parts.map((p) => {
      const member = memberOf(p.path), e = arch.find(member);
      let tris = null, groups = null, moving = 0;
      if (e) { const m = parseMsh(arch.read(e)); tris = m.indices.length / 3; groups = m.groups.length; if (m.gtom && m.matl) { const idn = new Set(); for (let i = 0; i < m.matl.length / 9; i++) { const t = m.matl.subarray(i * 9, i * 9 + 9); if (t.some((v, k) => v !== [0, 0, 0, 0, 0, 0, 1, 1, 1][k])) idn.add(i); } moving = [...m.gtom].filter((g) => idn.has(g)).length; } }
      const k = [...gen.files.keys()].find((x) => x.toLowerCase() === member.toLowerCase());
      let after = null, by = null, aG = null;
      if (k) { const m = parseMsh(gen.files.get(k)); after = m.indices.length / 3; aG = m.groups.length; by = gen.by.get(k); }
      return { lod: p.lod, file: p.file, tris, groups, moving, after, by };
    });
    const att = r.model.attach.length;
    const row = { zone: z, records: [r.name], mesh: parts[0].file, att, lods };
    seen.set(key, row); rows.push(row);
  }
}
if (jsonOut) fs.writeFileSync(jsonOut, JSON.stringify(rows, null, 1));
if (md) {
  console.log('| zone | records | LOD0 mesh | LODs (from: game tris -> generated by) | moving groups (LOD0) |\n|---|---|---|---|---|');
  for (const r of rows) console.log(`| ${r.zone} | ${r.records.join(' ')} | ${r.mesh}${r.att ? ` (+${r.att} att)` : ''} | ${r.lods.map((l) => `${l.lod}: ${l.tris ?? '?'}${l.after != null ? ` -> ${l.after} ${l.by}` : ''}`).join('; ')} | ${r.lods[0].moving} / ${r.lods[0].groups} |`);
} else for (const r of rows) console.log(r.zone, r.records.join(','), r.mesh, r.lods.map((l) => `${l.lod}:${l.tris}${l.after != null ? '->' + l.after + l.by : ''}`).join(' '));

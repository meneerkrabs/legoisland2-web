#!/usr/bin/env node
// M5 hub survey (docs/re/m5/foundation-ctors.md): per hub and per story node the behaviour constructors the EMULATED set-up attaches (count per constructor address,
// name, whether the port registers it, size of the constructor and of its handler functions in decompile lines). Usage:
//   node tools/m5-hub-survey.mjs [--decomp /Users/sander/Documents/basdebeer-tools/decomp-le2] [--out docs/re/m5/foundation-ctors.md]
import fs from 'node:fs';
import path from 'node:path';
import { standaloneCtx } from './lib/ctx-standalone.mjs';
import { loadExe, sceneOf } from './lib/engine-load.mjs';
import { profileFor, registeredCtors } from '../src/game/setup.ts';
import { zoneCodeIndex, readZoneTable } from '../src/formats/zonesetup.ts';
import '../src/zones/index.ts';

const args = process.argv.slice(2);
const opt = (n, d) => { const i = args.indexOf(n); return i < 0 ? d : args[i + 1]; };
const decomp = opt('--decomp', '/Users/sander/Documents/basdebeer-tools/decomp-le2');
const outFile = opt('--out', 'docs/re/m5/foundation-ctors.md');
const HUBS = {
  z07CSI: [15, 16, 17, 19, 20, 21, 22, 24, 25, 27, 28, 29], z13CAI: [33, 51], z14OSD: [34, 45], z16PYA: [36, 38, 40], z23DIP: [47, 50], z40OGL: [64, 66],
};
const ctx = standaloneCtx();
const pe = loadExe(ctx.dataRoot);
const starts = pe.functionStarts();
const reg = new Set(registeredCtors());
/** constructors the port covers without a registered node: the sky / sea / seabed records are drawn by src/render/environment.ts (M4 WP7) */
const ENV = new Set([0x4266ca, 0x426915, 0x426da4]);

// decompile line counts per function
const lines = new Map();
{
  const src = fs.readFileSync(path.join(decomp, 'LE2.c'), 'latin1').split('\n');
  let cur = -1;
  for (const l of src) {
    const m = /^\/\/ ==== \S+ @ ([0-9a-f]+)/.exec(l);
    if (m) { cur = parseInt(m[1], 16); lines.set(cur, 0); } else if (cur >= 0) lines.set(cur, lines.get(cur) + 1);
  }
}
const fnEnd = (a) => { let lo = 0, hi = starts.length - 1, i = -1; while (lo <= hi) { const m = (lo + hi) >> 1; if (starts[m] <= a) { i = m; lo = m + 1; } else hi = m - 1; } return i >= 0 && i + 1 < starts.length ? starts[i + 1] : a + 0x400; };
/** the handler table(s) a constructor stores into its node (`mov [reg + 4], imm32` with the table in .data holding code addresses): the handler functions */
function handlers(ctor) {
  const out = [];
  const end = fnEnd(ctor);
  for (let a = ctor; a < end - 7; a++) {
    if (pe.byte ? false : false) break;
    const b0 = pe.u32(a) & 0xff, b1 = (pe.u32(a) >> 8) & 0xff, b2 = (pe.u32(a) >> 16) & 0xff;
    if (b0 !== 0xc7 || b1 < 0x40 || b1 > 0x47 || b1 === 0x44 || b2 !== 0x04) continue;
    const tbl = pe.u32(a + 3);
    if (tbl < 0x8a0000 || tbl > 0x9f0000) continue;
    for (let k = 0; k < 8; k++) { const f = pe.u32(tbl + 4 * k); if (f >= 0x401000 && f < 0x85e000) out.push(f); else break; }
    if (out.length) break;
  }
  return out;
}
const hex = (v) => '0x' + v.toString(16);
const md = [];
md.push('# M5 survey: behaviour constructors attached by the emulated set-up of every hub', '',
  'Generated by `node tools/m5-hub-survey.mjs` (the x86 emulation of each hub\'s set-up root for every story node that maps to the hub; counts = attaches per constructor).',
  '`port` = `yes`: a constructor registered with `registerCtor` after `import src/zones/index.ts` (shared island families, the engine core, the mini-games); `env`: sky / sea / seabed records drawn by `src/render/environment.ts`; `-`: unported (hub-specific, or shared by several hubs).',
  '`ctor` / `handlers` = size in decompile lines (LE2.c) of the constructor and of the handler functions its node table points at (the `mov [node + 4], table` of the constructor; `?` = not found).', '');
const summary = [];
for (const [zone, nodes] of Object.entries(HUBS)) {
  const scene = sceneOf(ctx, zone);
  const archive = ctx.archives.find((a) => a.name.toLowerCase() === zone.toLowerCase());
  const code = zoneCodeIndex(pe).get(zone.toLowerCase());
  const table = readZoneTable(pe).find((t) => t.run >= code.lo && t.run < code.hi);
  const per = new Map();   // ctor -> { name, counts: node -> n }
  const emus = [];
  for (const node of nodes) {
    const m = new Map([[0x58, node], [2, 1]]);
    const emu = profileFor(zone, pe, scene, undefined, { emuVars: { get: (i) => m.get(i) ?? 0, set: (i, v) => m.set(i, v) }, archive }).emu;
    emus.push(emu);
    for (const a of emu.attaches) {
      const e = per.get(a.ctor) ?? per.set(a.ctor, { name: a.ctorName, counts: new Map(), recs: new Set() }).get(a.ctor);
      e.counts.set(node, (e.counts.get(node) ?? 0) + 1);
      e.recs.add(a.record);
    }
  }
  md.push(`## ${zone} (zone table index ${table?.index}, kind ${table?.kind}, run function ${hex(table?.run ?? 0)}, region ${hex(code.lo)}..${hex(code.hi)}, loader ${hex(code.loader)}, set-up root ${hex(code.root)})`, '');
  md.push(`Story nodes: ${nodes.join(', ')}. Emulated attaches per node: ${nodes.map((n, i) => `${n}: ${emus[i].attaches.length}`).join(', ')}. Cutscene slots: ${[...new Set(emus.flatMap((e) => e.cutscenes.map((c) => `${c.slot}:${c.name}`)))].join(', ') || 'none'}.`);
  md.push(`Dictionaries built by the loader / set-up: ${emus[0].dictionaries.all.map((d) => `${d.entries.size} names (capacity ${d.capacity}, built by ${hex(d.builtBy)})`).join('; ')}. Waypoint maps: ${emus[0].waypointMaps.map((w) => `${w.index}: ${(w.path ?? '').split('\\').pop()}`).join(', ')}. HUD hints: ${emus[0].hudHints.length}.`, '');
  md.push(`| ctor | name | port | ctor / handlers (lines) | records | ${nodes.map((n) => 'n' + n).join(' | ')} |`, `|---|---|---|---|---|${nodes.map(() => '---').join('|')}|`);
  const rows = [...per].sort((a, b) => [...b[1].counts.values()].reduce((x, y) => x + y, 0) - [...a[1].counts.values()].reduce((x, y) => x + y, 0));
  let unported = 0, unportedAttaches = 0, unportedLines = 0, total = 0;
  for (const [ctor, e] of rows) {
    const h = handlers(ctor);
    const tot = [...e.counts.values()].reduce((x, y) => x + y, 0);
    const maxN = Math.max(...e.counts.values());
    total += maxN;
    const ported = reg.has(ctor) || ENV.has(ctor);
    const hl = h.length ? h.map((f) => lines.get(f) ?? '?').join('+') : '?';
    if (!ported) { unported++; unportedAttaches += maxN; unportedLines += (lines.get(ctor) ?? 0) + h.reduce((s, f) => s + (lines.get(f) ?? 0), 0); }
    md.push(`| ${hex(ctor)} | ${e.name ?? ''} | ${reg.has(ctor) ? 'yes' : ENV.has(ctor) ? 'env' : '-'} | ${lines.get(ctor) ?? '?'} / ${hl}${h.length ? ' (' + h.map(hex).join(' ') + ')' : ''} | ${e.recs.size} | ${nodes.map((n) => e.counts.get(n) ?? 0).join(' | ')} |`);
    void tot;
  }
  md.push('', `${rows.length} constructors, ${unported} unported (about ${unportedAttaches} attaches at most per node, ${unportedLines} decompile lines of constructors + handlers).`, '');
  summary.push(`| ${zone} | ${rows.length} | ${unported} | ${unportedLines} | ${Math.max(...emus.map((e) => e.attaches.length))} |`);
}
md.splice(6, 0, '| hub | constructors | unported | lines (ctor + handlers, unported) | max attaches per node |', '|---|---|---|---|---|', ...summary, '');
fs.writeFileSync(outFile, md.join('\n') + '\n');
console.log(`wrote ${outFile}`);

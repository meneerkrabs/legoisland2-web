#!/usr/bin/env node
// z42BRP: records the roof games the differential test (tools/tests/m7-z42BRP-emu.mjs) replays: the look-ahead bot (Phase2Bot, src/zones/z42BRP/bot.ts) plays the roof on the port's
// world (the same oracle setup as the test: scripted random numbers / clock / cutscene) and its buttons are stored run-length encoded in src/zones/z42BRP/bot-plan-roof.ts.
// A recorded game is only valid for the same port code, seed and dt (the bots' start places depend on the clock); the test checks that the replay still ends the game.
//   node tools/lib/z42brp-roofplan.mjs [--write]
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { standaloneCtx } from './ctx-standalone.mjs';
import { createBrpOracle, portTick } from './m7-z42BRP-emu.mjs';
import { Phase2Bot } from '../../src/zones/z42BRP/bot.ts';
import { ZoneLoop, PepBrpNode } from '../../src/zones/z42BRP/nodes.ts';
import { PLAN1_DT05 } from '../../src/zones/z42BRP/bot-plan.ts';
import { VAR } from '../../src/zones/z42BRP/rules.ts';

const here = path.dirname(fileURLToPath(import.meta.url));
const ctx = standaloneCtx();
/** specs: key -> { dt, seed, full } (full: the recorded side-run plan first, then the roof; otherwise the phase variable is set to 2 at tick 2) */
export const SPECS = { d1s1: { dt: 1, seed: 1 }, d1s2: { dt: 1, seed: 2 }, d05s1: { dt: 0.5, seed: 1 }, f05s1: { dt: 0.5, seed: 1, full: true } };

function record({ dt, seed, full }) {
  const E = createBrpOracle(ctx, { dt, seed });
  PepBrpNode.widenTrigger = false;
  const P = E.P, S = E.S;
  const bot = new Phase2Bot(P, new ZoneLoop(), { horizon: Math.round(70 / dt) });
  const plan = [];
  for (let i = 0; i < 16 / dt; i++) plan.push(0);
  if (full) for (const [m, n] of PLAN1_DT05) for (let i = 0; i < n; i++) plan.push(m);
  const masks = [];
  let endAt = -1;
  for (let t = 0; t < 20000; t++) {
    let h;
    if (!full) { if (t === 2) P.vars.set(VAR.PHASE, 2); h = t < 3 ? 0 : bot.step(); }
    else h = P.vars.get(VAR.PHASE) === 2 ? bot.step() : (plan[t] ?? 0);
    masks.push(h);
    portTick(E, null, null, h);
    if (S.endState > 0 && endAt < 0) endAt = t;
    if (endAt >= 0 && t > endAt + Math.round(120 / dt)) break;
  }
  PepBrpNode.widenTrigger = true;
  const from = full ? 0 : 3, rle = [];
  for (const m of masks.slice(from)) { if (rle.length && rle[rle.length - 1][0] === m) rle[rle.length - 1][1]++; else rle.push([m, 1]); }
  return { rle, ticks: masks.length, endAt, hits: S.hits, endState: S.endState };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const out = {};
  for (const [k, spec] of Object.entries(SPECS)) {
    const t0 = Date.now();
    const r = record(spec);
    console.log(k, JSON.stringify(spec), 'ticks', r.ticks, 'end at', r.endAt, 'end state', r.endState, 'runs', r.rle.length, ((Date.now() - t0) / 1000 | 0) + ' s');
    out[k] = r.rle;
  }
  if (process.argv.includes('--write')) {
    const file = path.join(here, '../../src/zones/z42BRP/bot-plan-roof.ts');
    fs.writeFileSync(file, `// z42BRP: recorded roof games of the look-ahead bot for the differential test (generated by tools/lib/z42brp-roofplan.mjs; run-length encoded button masks [mask, ticks]).
// d1s1 / d1s2: dt = 1, seeds 1 / 2, the phase variable set to 2 at tick 2 (the plan starts at tick 3); d05s1: dt = 0.5; f05s1: dt = 0.5, the whole game from tick 0 (the side-run plan of
// bot-plan.ts, then the roof). Valid only for the port code, the seed and the dt they were recorded with.
export const ROOF_PLANS: Record<string, [number, number][]> = ${JSON.stringify(out)};
`);
    console.log('written', file);
  }
}

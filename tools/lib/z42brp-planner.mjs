#!/usr/bin/env node
// z42BRP: finds the run up the tower (phase 1) by beam search over button macros, running the real node code on copies of the world (src/zones/z42BRP/bot.ts snapshot /
// restore). The three stages are the two switches and the lift (the lift ends the side run). Writes the run-length encoded button masks to src/zones/z42BRP/bot-plan.ts.
//   node tools/lib/z42brp-planner.mjs [step=5] [width=60] [maxIterations=900] [--write] [--dt=0.5]
// --dt=0.5 plans the 60 Hz step (world.dt = 0.5; the macros are twice as many ticks: use step 10); the plan is stored as PLAN1_DT05 (the dt = 1 plan is PLAN1).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { Archive } from '../../src/formats/archive.ts';
import { newGame, tick, capture, restore, BTN } from './z42brp-sim.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const args = process.argv.slice(2).filter((a) => !a.startsWith('--'));
const DT = +(process.argv.find((a) => a.startsWith('--dt='))?.slice(5) ?? 1);
const STEP = +args[0] || 5, WIDTH = +args[1] || 60, MAXIT = +args[2] || 900;
const dataRoot = path.join(here, '../../public/data/le2');
const dataDir = path.join(dataRoot, '_data');
const archive = new Archive('z42BRP', fs.readFileSync(path.join(dataDir, 'z42BRP.bod')), fs.readFileSync(path.join(dataDir, 'z42BRP.bob')));
const ctx = { dataRoot, archives: [archive] };
const { w, S } = newGame(ctx);
w.dt = DT;
for (let i = 0; i < 16 / DT; i++) tick(w, 0);     // the hold at the start

const ACTIONS = [[BTN.LEFT, STEP], [BTN.LEFT | BTN.ALT, 1, BTN.LEFT, STEP - 1], [0, STEP], [BTN.RIGHT, STEP]];
const STAGES = [{ rec: 15, flag: 'sw1' }, { rec: 16, flag: 'sw2' }, { rec: 39, flag: 'lift' }];
const wrap = (d) => { d %= 2 * Math.PI; return d < 0 ? d + 2 * Math.PI : d; };
function expand(node, act) {
  restore(w, node.snap);
  const seq = [];
  for (let k = 0; k < act.length; k += 2) for (let i = 0; i < act[k + 1]; i++) { tick(w, act[k]); seq.push(act[k]); }
  return { snap: capture(w), seq: node.seq.concat(seq) };
}
function cost(c, st) {
  const m = c.snap.recs[90].m, t = c.snap.recs[st.rec].m;
  const a = Math.atan2(m[12], m[14]), at = Math.atan2(t[12], t[14]);
  const d = Math.abs(wrap(a - at + Math.PI) - Math.PI);
  const dy = Math.abs(t[13] - m[13]);
  return (dy > 3 ? dy * 10 : 0) + (dy < 6 ? d * 5 : 0);
}
let stage = 0;
let beam = [{ snap: capture(w), seq: [] }];
const t0 = Date.now();
for (let it = 0; it < MAXIT && stage < STAGES.length; it++) {
  const st = STAGES[stage];
  const cand = [];
  let done = null;
  for (const n of beam) for (const a of ACTIONS) {
    const c = expand(n, a);
    if (c.snap.st.reset5ec) continue;
    const node = c.snap.nodes.find((x) => x.kind === 'pepbrp');
    c.air = node.air; c.y = c.snap.recs[90].m[13];
    c.cost = cost(c, st);
    if (node[st.flag]) { done = c; break; }
    cand.push(c);
  }
  if (done) { console.log(`stage ${stage} (${st.flag}) done at tick ${done.seq.length} (${((Date.now() - t0) / 1000) | 0} s)`); beam = [done]; stage++; continue; }
  const cells = new Map();
  for (const c of cand) { const m = c.snap.recs[90].m; const k = `${Math.round(Math.atan2(m[12], m[14]) * 20)}|${Math.round(c.y)}|${c.air ? 1 : 0}`; const o = cells.get(k); if (!o || c.cost < o.cost) cells.set(k, c); }
  beam = [...cells.values()].sort((a, b) => a.cost - b.cost).slice(0, WIDTH);
  if (it % 25 === 0) { const b = beam[0]; const m = b.snap.recs[90].m; console.log(it, 'stage', stage, 'ticks', b.seq.length, 'y', b.y.toFixed(1), 'ang', Math.atan2(m[12], m[14]).toFixed(2), 'cost', b.cost.toFixed(2)); }
  if (!beam.length) { console.log('dead end'); process.exit(1); }
}
if (stage < STAGES.length) { console.log('not found'); process.exit(1); }
const seq = beam[0].seq;
const rle = [];
for (const m of seq) { if (rle.length && rle[rle.length - 1][0] === m) rle[rle.length - 1][1]++; else rle.push([m, 1]); }
console.log('FOUND', seq.length, 'ticks,', rle.length, 'runs');
if (process.argv.includes('--write')) {
  const file = path.join(here, '../../src/zones/z42BRP/bot-plan.ts');
  const old = await import(file + '?t=' + Date.now());
  const plans = { PLAN1: old.PLAN1, PLAN1_DT05: old.PLAN1_DT05 ?? [] };
  plans[DT === 1 ? 'PLAN1' : 'PLAN1_DT05'] = rle;
  fs.writeFileSync(file, `// z42BRP: the recorded runs up the tower for the scripted player (run-length encoded button masks: [mask, ticks]), generated by tools/lib/z42brp-planner.mjs from the real node code
// (the start hold of 16 ticks (32 at dt = 0.5) is not part of it: the plan starts with the first tick the run takes input; the world must be a fresh phase-1 game with the seed the tests use).
// PLAN1: world.dt = 1 (30 Hz, with the widened switch probe); PLAN1_DT05: world.dt = 0.5 (60 Hz, the original's own switch probe).
export const PLAN1: [number, number][] = ${JSON.stringify(plans.PLAN1)};
export const PLAN1_DT05: [number, number][] = ${JSON.stringify(plans.PLAN1_DT05)};
`);
  console.log('written', file);
}

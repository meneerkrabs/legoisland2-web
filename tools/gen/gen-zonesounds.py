#!/usr/bin/env python3
# Generates src/audio/zonesounds.ts: the sounds the original loads (SoundClass caches) at the start of every zone, from the Ghidra decompile
# (basdebeer-tools/decomp-le2: LE2.asm.txt, tools/zonemap.py). Run from decomp-le2 with its venv:
#   cd /Users/sander/Documents/basdebeer-tools/decomp-le2 && ../venv/bin/python -I /Users/sander/Documents/legoeiland2-web/tools/gen/gen-zonesounds.py > /Users/sander/Documents/legoeiland2-web/src/audio/zonesounds.ts
# Method: every `call 0x443580` (2D load, FUN_00443580) / `call 0x4433b0` (3D load, FUN_004433b0) whose argument is the immediately preceding `push imm`.
# The per-zone sound-setup function is the one that calls the cache reset FUN_004359d5 (28 of them) plus FUN_00708640 (z22BIP, no reset call: the zone loop resets).
import sys, re, bisect, collections
sys.path.insert(0, '/Users/sander/Documents/basdebeer-tools/decomp-le2/tools')
import zonemap as zm
import fn
from cg import callers
P = '/Users/sander/Documents/basdebeer-tools/decomp-le2/'
asm = []
for l in open(P + 'LE2.asm.txt', encoding='latin1'):
    m = re.match(r'([0-9a-f]{8}): (\S+)\s+(.*)', l)
    if m: asm.append((int(m.group(1), 16), m.group(3).strip()))
addrs = [a for a, _ in asm]
def fn_end(s): return fn.keys[bisect.bisect_right(fn.keys, s)]
def loads_of(s):
    e = fn_end(s)
    out = []
    i = bisect.bisect_left(addrs, s)
    while i < len(asm) and asm[i][0] < e:
        a, ins = asm[i]
        if ins in ('call 0x443580', 'call 0x4433b0'):
            pi = asm[i - 1][1]
            m = re.match(r'push (0x[0-9a-f]+|\d+)$', pi)
            if not m: out.append(('2d' if ins.endswith('443580') else '3d', None, a))
            else: out.append(('2d' if ins.endswith('443580') else '3d', int(m.group(1), 0), a))
        i += 1
    return out, e
setups = {}
for c in callers[0x4359d5]:
    if c == 0x4359d5: continue
    setups[zm.zone_of(c)] = c
setups['z22BIP'] = 0x708640
setups['z60FRE'] = 0x53e7c0   # the front end's start-up after the movie (FUN_0041b9b1 case 0x16: FUN_0053e7c0, FUN_004b0240, FUN_004b0b37) loads z03PPH's list; shared with z03PPH
def fmt(l): return '[' + ', '.join("['%s', %d]" % (k, i) for k, i, _ in l) + ']'
print('// GENERATED by tools/gen/gen-zonesounds.py from the Ghidra decompile of LEGO eiland 2.exe: do not edit by hand (docs/re/audio.md section 11).')
print('// The sounds the original loads into its SoundClass caches (FUN_00443580 = 2D slot, FUN_004433b0 = 3D slot, one slot per call: a sound loaded n times has n')
print('// independent voices) by the zone\'s sound-setup function; loaded in this order before the zone loop runs (the zone switch resets both caches first, FUN_004359d5).')
print("export type SoundLoad = readonly ['2d' | '3d', number];")
print('export interface ZoneSoundSetup { /** VA of the setup function and the VA where the next function starts */ fn: number; end: number; loads: readonly SoundLoad[] }')
print()
print('export const ZONE_SOUND_SETUP: Readonly<Record<string, ZoneSoundSetup>> = {')
for z in sorted(setups, key=lambda z: setups[z]):
    s = setups[z]
    if z == 'z60FRE':
        l, e = loads_of(0x53e7c0)
        l2, _ = loads_of(0x47172c)   # the zone function itself (FUN_0047172c): one 3D load of SND_SILENCE
        l = l + l2
        print("  // z60FRE: no setup of its own in the zone function; the menu code (FUN_0041b9b1 line 13045) loads z03PPH's list, FUN_004b0240 and FUN_004b0b37")
        print("  z60FRE: { fn: 0x53e7c0, end: 0x%x, loads: %s }," % (e, fmt(l)))
        continue
    l, e = loads_of(s)
    assert all(i is not None for _, i, _ in l), (z, hex(s))
    print("  %s: { fn: 0x%x, end: 0x%x, loads: %s }," % (z, s, e, fmt(l)))
print('};')
print()
print('/** shared loaders: FUN_004b0240 (menu clicks, every zone loop through FUN_0041b40e), FUN_004b0b37 + FUN_004b0f16 (the walking Pepper, SGwalk constructor FUN_0042f470) */')
print('export interface SoundSet { /** [start, end) VA ranges of the loading functions */ fn: readonly (readonly [number, number])[]; loads: readonly SoundLoad[] }')
sets = collections.OrderedDict()
sets['MENU'] = [0x4b0240]
sets['WALK'] = [0x4b0b37, 0x4b0f16]
sets['SGBOAT'] = [0x430e6c]
sets['PTERA'] = [0x4bb1a6]
print('export const SOUND_SETS: Readonly<Record<string, SoundSet>> = {')
for k, fs in sets.items():
    allv = []
    rng = []
    for f in fs:
        l, e = loads_of(f)
        assert all(i is not None for _, i, _ in l)
        allv += l
        rng.append('[0x%x, 0x%x]' % (f, e))
    print("  %s: { fn: [%s], loads: %s }," % (k, ', '.join(rng), fmt(allv)))
print('};')
print()
# which zones register which constructor classes (immediate `push <ctor>` inside the zone's region)
ctors = {0x42f470: 'WALK', 0x430e6c: 'SGBOAT', 0x4bb1a6: 'PTERA'}
found = collections.defaultdict(set)
for a, ins in asm:
    m = re.match(r'push (0x[0-9a-f]+)$', ins)
    if m and int(m.group(1), 16) in ctors:
        z = zm.zone_of(a)
        if z: found[z].add(ctors[int(m.group(1), 16)])
found['z60FRE'].add('WALK')   # FUN_0041b9b1 case 0x16 calls FUN_004b0b37 directly
print('/** the constructor classes (keys of SOUND_SETS) a zone registers in its builder: their constructors load the set when the object is created at zone set-up */')
print('export const ZONE_CLASS_SETS: Readonly<Record<string, readonly string[]>> = {')
for z in sorted(found): print("  %s: [%s]," % (z, ', '.join("'%s'" % c for c in sorted(found[z]))))
print('};')

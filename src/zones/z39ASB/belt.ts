/** speed regime (max speed, asteroid spacing) of a shuttle z (FUN_007b82dd top, FUN_007b9917) */
export function regimeOf(z: number): { maxSpeed: number; spacing: number } {
  for (const [lim, max, sp] of C.REGIMES) if (z <= lim) return { maxSpeed: max, spacing: sp };
  return { maxSpeed: C.REGIMES[3][1], spacing: C.REGIMES[3][2] };
}

/** FUN_007b7e9a: medal index of a final score: 0 bronze, 1 silver, 2 gold */
export function medalIndex(score: number): 0 | 1 | 2 {
  return score > C.GOLD_ABOVE ? 2 : score > C.SILVER_ABOVE ? 1 : 0;
}

// ---------------------------------------------------------------------------------------------------------------- random numbers
/**
 * The zone's random numbers: the C runtime's rand() (FUN_0085daf0, the shared generator src/game/crt.ts unless a test injects a scripted source, 0 .. 32767) and FUN_004388ae(x) on top of it
 * (`(float) rand() / 32767.0f * x`, every operation float32; x <= 0 draws nothing).
 */
export class BeltRng {
  src: RandSource;
  constructor(src: RandSource = crtRand) { this.src = src; }
  next(): number { return this.src(); }
  /** FUN_004388ae(x) */
  range(x: number): number { return randFrom(this.src, x); }
}

// ---------------------------------------------------------------------------------------------------------------- engine sound pitch
/**
 * The pitch counters of the engine sounds (FUN_007b6f1f spool of the thrust, FUN_007b6de3 gyro and thrust drop while steering; all in Hz offsets of 22050 = 0x5622).
 * `thrustRate` / `gyroRate` are the rates FUN_00443600 gets.
 */
export class EngineModel {
  /** DAT_05d5d514: thrust spool 0..0x5622, +245 per tick while flying */
  spool = 0;
  /** DAT_05d5d52c: gyro pitch 0..0xb86, +98 per tick while steering, -98 otherwise */
  gyro = 0;
  /** DAT_05d5d4f8: thrust pitch drop 0..0xfd2, +270 while steering, -200 otherwise */
  drop = 0;
  /** the gyro sound was stopped (FUN_007b6f1f(0) with a spool above 0) */
  gyroStopped = false;
  get thrustRate() { return this.spool + 0x5622 - this.drop; }
  get gyroRate() { return this.gyro + 0x5622; }
  /**
   * the pitches the loops were last SET to (FUN_00443600 calls): FUN_007b6f1f sets the thrust to spool + 0x5622 (no drop!), FUN_007b6de3 sets the gyro to gyro + 0x5622 and the thrust
   * to spool + 0x5622 - drop; only the calls that change a counter set anything (M7 oracle: the port used `thrustRate` every tick, which kept subtracting the drop after the steering stopped)
   */
  thrustHz = 0x5622; gyroHz = 0x5622;
  /** FUN_007b6f1f(on): the counter moves by 245 * DAT_008b1718 (`ftol(counter +- 245 * dt)`: truncated every call, so at dt 0.5 it moves by 122 per call) */
  spoolStep(on: boolean, dt = 1) {
    if (on) { if (this.spool < 0x5622) { this.spool = Math.trunc(this.spool + 245 * dt); this.thrustHz = this.spool + 0x5622; } }
    else if (this.spool > 0) { this.spool = Math.trunc(this.spool - 245 * dt); this.thrustHz = this.spool + 0x5622; this.gyroStopped = true; }
  }
  /** FUN_007b6de3(moving): the gyro moves by 98 * dt, the thrust drop by 270 * dt (up) / 200 * dt (down) */
  steerStep(moving: boolean, dt = 1) {
    if (moving) {
      if (this.gyro < 0xb86) { this.gyro = Math.trunc(this.gyro + 98 * dt); this.gyroHz = this.gyro + 0x5622; }
      if (this.drop < 0xfd2) { this.drop = Math.trunc(this.drop + 270 * dt); this.thrustHz = this.spool + 0x5622 - this.drop; }
    } else {
      if (this.gyro > 0) { this.gyro = Math.trunc(this.gyro - 98 * dt); this.gyroHz = this.gyro + 0x5622; }
      if (this.drop > 0) { this.drop = Math.trunc(this.drop - 200 * dt); this.thrustHz = this.spool + 0x5622 - this.drop; }
    }
  }
}


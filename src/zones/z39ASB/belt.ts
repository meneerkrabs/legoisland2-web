// Pure TypeScript (no DOM): the whole simulation of the zone's loop (FUN_007b63f6, mode 2), driven tick by tick with the held buttons, so node tests can play it.
// Ported from the decompile (docs/re/m3/z39ASB.md has the table of addresses):
